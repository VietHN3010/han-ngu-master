#!/usr/bin/env node
/**
 * Builds src/notes.js (window.LESSON_NOTES) from the cleaned slide audit.
 *
 *   node scripts/build-notes.js [path/to/slide-audit]
 *
 * Input: <audit>/clean_*.json — arrays of
 *   { lesson, category, word, title, content, slide, deck, fixes }
 * extracted from the teacher's HSK 1-2 slides (default audit dir: ../slide-audit, outside the repo).
 *
 * Output shape:
 *   LESSON_NOTES.words[wordId]   -> notes attached to one vocabulary word
 *   LESSON_NOTES.lessons[lessonId] -> lesson-level notes (grammar, usage, extra words, culture)
 *   lessons[0] holds the intro deck (phonetics, Chinese characters) used by the Kiến thức page.
 */
const fs = require('fs');
const path = require('path');
const vm = require('vm');

const ROOT = path.resolve(__dirname, '..');
const AUDIT = path.resolve(process.argv[2] || path.join(ROOT, '..', 'slide-audit'));
const OUT = path.join(ROOT, 'src', 'notes.js');
const CATS = ['chiet_tu', 'cach_dung', 'cau_vi_du', 'tu_mo_rong', 'ngu_phap', 'ngu_am', 'van_hoa', 'khac'];

const sandbox = { window: {} };
vm.createContext(sandbox);
vm.runInContext(fs.readFileSync(path.join(ROOT, 'src', 'data.js'), 'utf8'), sandbox);
const lessons = sandbox.window.CHINESE_DATA.lessons;

const files = fs.readdirSync(AUDIT).filter((f) => /^clean_[A-Z]\.json$/.test(f)).sort();
if (!files.length) {
  console.error(`No clean_*.json found in ${AUDIT}`);
  process.exit(1);
}

const words = {};
const lessonNotes = {};
let attached = 0;
let lessonLevel = 0;
let skipped = 0;

for (const f of files) {
  const items = JSON.parse(fs.readFileSync(path.join(AUDIT, f), 'utf8'));
  for (const it of items) {
    if (!it || !it.content || !CATS.includes(it.category)) { skipped++; continue; }
    const note = { c: it.category, t: String(it.title || '').trim(), x: String(it.content).trim(), s: `${it.deck || ''}#${it.slide || ''}` };
    const lesson = lessons.find((l) => l.id === it.lesson);
    const w = it.word && lesson ? lesson.words.find((x) => x.hanzi === it.word) : null;
    if (w) {
      (words[w.id] = words[w.id] || []).push(note);
      attached++;
    } else {
      (lessonNotes[it.lesson] = lessonNotes[it.lesson] || []).push(note);
      lessonLevel++;
    }
  }
}

const order = (a, b) => CATS.indexOf(a.c) - CATS.indexOf(b.c);
Object.values(words).forEach((arr) => arr.sort(order));
Object.values(lessonNotes).forEach((arr) => arr.sort(order));

const body = `/**
 * Lesson notes from the teacher's HSK 1-2 slides: chiết tự (character components and memory tricks),
 * usage notes, example sentences, extra vocabulary, grammar, phonetics and culture.
 * AUTO-GENERATED by scripts/build-notes.js from slide-audit/clean_*.json. Do not edit by hand:
 * fix the audit JSON and re-run the script.
 */
window.LESSON_NOTES = ${JSON.stringify({ words, lessons: lessonNotes })};
`;
fs.writeFileSync(OUT, body, 'utf8');
console.log(`notes.js: ${attached} word notes on ${Object.keys(words).length} words, ${lessonLevel} lesson notes, ${skipped} skipped (${files.join(', ')})`);

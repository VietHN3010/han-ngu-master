#!/usr/bin/env node
/**
 * Builds the HSK 3 lessons from the teacher's slides.
 *
 *   node scripts/build-hsk3.js [path/to/slide-audit]
 *
 * Input:  <audit>/hsk3/lesson_31.json … (one per lesson, produced from slide-audit/slide-text/HSK3_*.txt)
 *         { lesson: {id, hsk, zh_title, pinyin_title, title, words, dialogue, grammar},
 *           grammar_exercises: [...GRAMMAR_DATA items], notes: [...clean notes] }
 * Output: src/data-hsk3.js     appends the lessons to window.CHINESE_DATA (data bundle)
 *         src/grammar-hsk3.js  appends the exercises to GRAMMAR_DATA (app bundle)
 *         <audit>/clean_H.json  lesson notes, picked up by scripts/build-notes.js
 */
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const AUDIT = path.resolve(process.argv[2] || path.join(ROOT, '..', 'slide-audit'));
const DIR = path.join(AUDIT, 'hsk3');

const files = fs.readdirSync(DIR).filter((f) => /^lesson_\d+\.json$/.test(f)).sort();
if (!files.length) {
  console.error(`No lesson_*.json in ${DIR}`);
  process.exit(1);
}

const lessons = [];
const exercises = [];
const notes = [];
for (const f of files) {
  const d = JSON.parse(fs.readFileSync(path.join(DIR, f), 'utf8'));
  const l = d.lesson;
  // Keep only the fields the app uses, in the same order as src/data.js
  lessons.push({
    id: l.id,
    hsk: l.hsk || 3,
    zh_title: l.zh_title,
    pinyin_title: l.pinyin_title,
    title: l.title,
    words: l.words.map((w, i) => {
      const o = { id: w.id || `w_${l.id}_${i + 1}`, hsk: l.hsk || 3, lesson: l.id, hanzi: w.hanzi, pinyin: w.pinyin, pos: w.pos, hanviet: w.hanviet, meaning: w.meaning };
      if (w.example) o.example = w.example;
      return o;
    }),
    dialogue: l.dialogue.map((x) => ({ ...(x.section ? { section: x.section } : {}), speaker: x.speaker, zh: x.zh, py: x.py, vi: x.vi })),
    grammar: l.grammar
  });
  (d.grammar_exercises || []).forEach((g) => exercises.push({ ...g, lesson: l.id, hsk: l.hsk || 3 }));
  (d.notes || []).forEach((n) => notes.push({ ...n, lesson: l.id }));
}
lessons.sort((a, b) => a.id - b.id);

const header = (what) => `/**
 * HSK 3 ${what} (Bài ${lessons[0].id}–${lessons[lessons.length - 1].id}) from the teacher's slides.
 * AUTO-GENERATED by scripts/build-hsk3.js from slide-audit/hsk3/lesson_*.json. Do not edit by hand.
 */
`;

fs.writeFileSync(path.join(ROOT, 'src', 'data-hsk3.js'), `${header('lessons')}(function () {
  const D = window.CHINESE_DATA;
  const extra = ${JSON.stringify(lessons)};
  extra.forEach((l) => { if (!D.lessons.some((x) => x.id === l.id)) D.lessons.push(l); });
  D.lessons.sort((a, b) => a.id - b.id);
  D.all_words = D.lessons.reduce((acc, l) => acc.concat(l.words || []), []);
  D.total_words = D.all_words.length;
  D.total_lessons = D.lessons.length;
})();
`, 'utf8');

fs.writeFileSync(path.join(ROOT, 'src', 'grammar-hsk3.js'), `${header('grammar exercises')}GRAMMAR_DATA.push(...${JSON.stringify(exercises)});
`, 'utf8');

fs.writeFileSync(path.join(AUDIT, 'clean_H.json'), JSON.stringify(notes, null, 1), 'utf8');

const words = lessons.reduce((a, l) => a + l.words.length, 0);
console.log(`HSK3: ${lessons.length} lessons, ${words} words, ${lessons.reduce((a, l) => a + l.dialogue.length, 0)} dialogue lines, ${exercises.length} exercises, ${notes.length} notes`);
